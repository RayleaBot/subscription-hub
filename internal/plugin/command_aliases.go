func addCommandAliases(commands map[string]commandRoute) error {
	for name, aliases := range commandAliasGroups {
		route, exists := commands[name]
		if !exists {
			continue
		}
		for _, alias := range aliases {
			if _, exists := commands[alias]; exists {
				return fmt.Errorf("duplicate command alias %q", alias)
			}
			commands[alias] = route
		}
	}
	return nil
}
